export const TODAS_LAS_LICENCIAS: LicenciaItem[] = [
  ...LICENCIAS_DOCENTES,
  ...LICENCIAS_AUXILIARES
];

/**
 * Búsqueda inteligente y multicriterio sobre la DB de Licencias
 */
export function buscarLicencias(
  query: string = "",
  filters: {
    tipoPersonal?: TipoPersonal | "todos";
    categoria?: CategoriaLicencia | "todas";
    conGoce?: "todos" | "con_goce" | "sin_goce" | "parcial";
  } = {}
): LicenciaItem[] {
  const cleanQ = query.trim().toLowerCase();
  const { tipoPersonal = "todos", categoria = "todas", conGoce = "todos" } = filters;

  return TODAS_LAS_LICENCIAS.filter(item => {
    if (tipoPersonal !== "todos" && item.tipoPersonal !== tipoPersonal) return false;
    if (categoria !== "todas" && item.categoria !== categoria) return false;
    if (conGoce === "con_goce" && item.conGoce !== true) return false;
    if (conGoce === "sin_goce" && item.conGoce !== false) return false;
    if (conGoce === "parcial" && item.conGoce !== "parcial") return false;

    if (!cleanQ) return true;

    const matchArticulo = item.articulo.toLowerCase().includes(cleanQ);
    const matchMotivo = item.motivoSae.toLowerCase().includes(cleanQ);
    const matchDescripcion = item.descripcion.toLowerCase().includes(cleanQ);
    const matchNormativa = item.marcoNormativo.toLowerCase().includes(cleanQ);
    const matchCondiciones = item.condicionesRequisitos.toLowerCase().includes(cleanQ);
    const matchAutoridad = item.autoridadOtorga.toLowerCase().includes(cleanQ);

    return matchArticulo || matchMotivo || matchDescripcion || matchNormativa || matchCondiciones || matchAutoridad;
  });
}

/**
 * Obtener un artículo específico por código y rol
 */
export function getLicenciaByArticulo(articulo: string, tipoPersonal?: TipoPersonal): LicenciaItem | null {
  const artClean = articulo.trim().toLowerCase();
  const list = tipoPersonal
    ? (tipoPersonal === "docente" ? LICENCIAS_DOCENTES : LICENCIAS_AUXILIARES)
    : TODAS_LAS_LICENCIAS;

  return list.find(item => {
    const itemArt = item.articulo.toLowerCase();
    return itemArt === artClean ||
      itemArt.replace(/\s+/g, "") === artClean.replace(/\s+/g, "") ||
      itemArt.replace(/\(aux\)/i, "").trim() === artClean.replace(/\(aux\)/i, "").trim();
  }) || null;
}

/**
 * Emparejar un motivo o tipo de ausencia registrada con la base de licencias oficial
 */
export function matchAusenciaConDBLicencias(motivo: string, tipo?: string): LicenciaItem | null {
  const text = `${tipo || ""} ${motivo || ""}`.toLowerCase();

  // 1. Coincidencia por código de artículo exacto o "art. XX"
  for (const item of TODAS_LAS_LICENCIAS) {
    const artCode = item.articulo.toLowerCase();
    const cleanArt = artCode.replace(/\(aux\)/i, "").trim();
    if (text.includes(artCode) || (cleanArt.length > 1 && text.includes(`art. ${cleanArt}`))) {
      return item;
    }
  }

  // 2. Coincidencia por motivo SAE o descripción
  for (const item of TODAS_LAS_LICENCIAS) {
    if (item.motivoSae.length > 5 && text.includes(item.motivoSae.toLowerCase())) {
      return item;
    }
    if (item.descripcion.length > 5 && text.includes(item.descripcion.toLowerCase())) {
      return item;
    }
  }

  return null;
}

/**
 * Métricas globales del catálogo normativo
 */
export function getStatsLicenciasDB() {
  const docentes = LICENCIAS_DOCENTES;
  const auxiliares = LICENCIAS_AUXILIARES;

  return {
    total: TODAS_LAS_LICENCIAS.length,
    docentesTotal: docentes.length,
    docentesConGoce: docentes.filter(d => d.conGoce === true).length,
    docentesSinGoce: docentes.filter(d => d.conGoce === false).length,
    docentesParcial: docentes.filter(d => d.conGoce === "parcial").length,
    auxiliaresTotal: auxiliares.length,
    auxiliaresConGoce: auxiliares.filter(a => a.conGoce === true).length,
    auxiliaresSinGoce: auxiliares.filter(a => a.conGoce === false).length,
    auxiliaresParcial: auxiliares.filter(a => a.conGoce === "parcial").length,
  };
}
